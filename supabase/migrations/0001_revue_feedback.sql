-- 0001 — Mode Revue : retours de recette posés sur les écrans du site.
--
-- Projet SITE uniquement (jamais le projet du BO : CLAUDE.md §2 et §16).
-- Ce fichier est la seule source des migrations de la base du site — un seul
-- repo possède les migrations de chaque base, sinon la panne est garantie.
--
-- Colonnes calquées sur la table homonyme du back-office : si un jour les deux
-- bases se rejoignent, la reprise est un simple COPY.

create table if not exists public.bo_feedback (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  auteur         text        not null default 'MAV',
  url            text        not null,
  page_titre     text,
  selecteur      text,
  element_texte  text,

  -- Coin haut-gauche de la zone si w_pct/h_pct sont renseignés,
  -- centre de l'épingle sinon. En % de la page, pour retrouver le point
  -- quelle que soit la largeur d'écran de celui qui relit.
  x_pct          numeric,
  y_pct          numeric,
  w_pct          double precision,
  h_pct          double precision,
  viewport_w     integer,

  gravite        text        not null default 'ecart'
                 check (gravite in ('bloquant', 'ecart', 'detail', 'idee')),
  commentaire    text        not null,

  -- Première capture, puis toutes : `capture_path` reste renseigné pour que
  -- les retours d'avant le multi-captures continuent de s'afficher.
  capture_path   text,
  captures       text[],

  statut         text        not null default 'ouvert'
                 check (statut in ('ouvert', 'corrige', 'ecarte')),
  reponse        text,
  traite_at      timestamptz
);

-- Le bouton de chaque écran ne lit que les retours ouverts de la page courante.
create index if not exists bo_feedback_ouverts_idx
  on public.bo_feedback (url, created_at desc)
  where statut = 'ouvert';

-- RLS activée, AUCUNE policy. CLAUDE.md §2 : « RLS activée sur toutes les
-- tables, sans exception ». Sans policy, les clés `anon` et `authenticated`
-- — publiques par conception — ne peuvent rien lire ni écrire. Seule la clé
-- `service_role`, qui ne vit que dans les route handlers serveur, passe.
alter table public.bo_feedback enable row level security;

-- Coffre des captures. Privé : une capture de recette montre souvent un écran
-- avec des données de test, parfois réalistes.
insert into storage.buckets (id, name, public)
values ('bo-files', 'bo-files', false)
on conflict (id) do nothing;
